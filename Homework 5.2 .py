# ДЗ 5.2: Калькулятор з можливістю повтору обчислень

while True:                                                # 1) Безкінечний цикл
    #   Дані від користувача
    num1 = float(input("Введіть перше число: "))
    operation = input("Введіть операцію (+, -, *, /): ")


    num2 = float(input("Введіть друге число: "))

    #  Перевіряємо ділення на нуль
    if operation == "/" and num2 == 0:                      #  Якщо операція "/" І друге число = 0
        result = "Помилка: дільник не може дорівнювати 0!"  #  Відразу готуємо повідомлення про помилку
    else:                                                   #  Інакше — рахуємо результат через match/case
        match operation:
            case "+":                                       #  Якщо "+" — додаємо
                result = num1 + num2
            case "-":                                       #  Якщо "-" — віднімаємо
                result = num1 - num2
            case "*":                                       #  Якщо "*" — множимо
                result = num1 * num2
            case "/":                                       #  Якщо "/" — ділимо

                result = num1 / num2
            case _:                                         #  Будь-який інший символ — помилка
                result = "Невідома операція!"

    # Виводимо результат
    print(f"Результат: {num1} {operation} {num2} = {result}")

    #  Питаємо, чи продовжувати
    answer = input("Продовжити? (у/y/n): ").lower()          #  Питаємо користувача
                                                             #     .lower() — щоб 'У' і 'Y' теж працювали

    match answer:
        case "у" | "y":                                      #  Якщо "у" (кирилична) або "y" (латинська)
            continue

        case _:                                              #  Будь-яка інша відповідь (n, no, ні, ...)
            print("До побачення!")
            break