# === ПРОСТОЙ КАЛЬКУЛЯТОР С ПРОВЕРКОЙ ДЕЛИТЕЛЯ ===

# 1. Просим пользователя ввести первое число.
num1 = float(input("Введите первое число: "))
# 2. Просим ввести знак операции.
operation = input("Введите операцию (+, -, *, /): ")
# 3. Просим ввести второе число.
num2 = float(input("Введите второе число: "))
# 4. Проверка деления на "0": если выбрано деление И второе число равно 0 —
#    делить нельзя. Сразу пишем ошибку и идём к печати (без вычисления).
if operation == "/" and num2 == 0:
    result = "Ошибка: делитель не может быть равен 0!"
else:
    match operation:
        # operation == "+" — складываем
        case "+":
            result = num1 + num2

        # operation == "-" — вычитаем второе из первого
        case "-":
            result = num1 - num2

        # operation == "*" — умножаем
        case "*":
            result = num1 * num2

        # operation == "/" — делим.
        case "/":
            result = num1 / num2

        case _:
            result = "Неизвестная операция! Используйте +, -, *, /"

# 5. Печатаем итог: либо число, либо сообщение об ошибке.
print(f"Результат: {num1} {operation} {num2} = {result}")